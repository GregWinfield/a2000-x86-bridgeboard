"""Reference implementation of the host-link protocol v1.0 (docs/hdl/host-link-protocol.md).

usage: python -I tools/hostlink/hostlink.py vectors     # print the normative test vectors (markdown)
       python -I tools/hostlink/hostlink.py vh <out.vh>  # write the vectors as a Verilog include

The RP2040 firmware and the Windows tools implement the same functions; the RTL testbench checks the FPGA
against the vectors produced here. CRC-16/IBM-3740 ("CCITT-FALSE"): width 16, poly 0x1021, init 0xFFFF,
not reflected, xorout 0x0000, check("123456789") = 0x29B1.
"""
from __future__ import annotations

import sys

PROTO_MAJOR, PROTO_MINOR = 1, 0
SYNC = 0xA0 | PROTO_MAJOR          # first command byte (MOSI)
RSYNC = 0x50 | PROTO_MAJOR         # first response byte (MISO); written last by the FPGA
MAX_WORDS = 128                    # SRAM burst limit (256 data bytes)
MAX_PAYLOAD = 3 + 2 * MAX_WORDS    # largest command payload: SRAM_WRITE address + data = 259 bytes

CMD = {"IDENTIFY": 0x01, "STATUS": 0x02, "GET_RESPONSE": 0x03, "RESET_LINK": 0x04, "ECHO": 0x05,
       "SRAM_WRITE": 0x10, "SRAM_READ": 0x11, "SRAM_WRITE_BE": 0x12, "REG_WRITE": 0x20, "REG_READ": 0x21}
RCODE = {"OK": 0x00, "ERR_CMD": 0x01, "ERR_LEN": 0x02, "ERR_ARG": 0x03}


def crc16(data: bytes, crc: int = 0xFFFF) -> int:
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def with_crc(body: bytes) -> bytes:
    c = crc16(body)
    return body + bytes([c >> 8, c & 0xFF])


def command(cmd: str, seq: int, payload: bytes = b"") -> bytes:
    """Command frame: SYNC CMD SEQ LEN_HI LEN_LO payload CRC_HI CRC_LO."""
    n = len(payload)
    assert n <= MAX_PAYLOAD
    return with_crc(bytes([SYNC, CMD[cmd], seq & 0xFF, n >> 8, n & 0xFF]) + payload)


def addr3(word_addr: int) -> bytes:
    assert 0 <= word_addr < (1 << 18)
    return bytes([word_addr >> 16, (word_addr >> 8) & 0xFF, word_addr & 0xFF])


def sram_write(seq, word_addr, words):
    assert 1 <= len(words) <= MAX_WORDS
    return command("SRAM_WRITE", seq, addr3(word_addr) + b"".join(bytes([w >> 8, w & 0xFF]) for w in words))


def sram_read(seq, word_addr, nwords):
    assert 1 <= nwords <= MAX_WORDS
    return command("SRAM_READ", seq, addr3(word_addr) + bytes([nwords & 0xFF]))   # 128 is sent as 0x80


def response(status: int, seq: int, rcode: int, payload: bytes = b"") -> bytes:
    """Response frame: RSYNC STATUS SEQ RCODE LEN_HI LEN_LO payload CRC_HI CRC_LO."""
    n = len(payload)
    return with_crc(bytes([RSYNC, status & 0xFF, seq & 0xFF, rcode, n >> 8, n & 0xFF]) + payload)


def check_response(frame: bytes):
    """Return (status, seq, rcode, payload) or raise ValueError."""
    if len(frame) < 8 or frame[0] != RSYNC:
        raise ValueError("no response (RSYNC)")
    n = (frame[4] << 8) | frame[5]
    total = 6 + n + 2
    if len(frame) < total or crc16(frame[:total]) != 0:
        raise ValueError("response CRC")
    return frame[1], frame[2], frame[3], frame[6:6 + n]


def vectors():
    """Normative vectors: (name, bytes)."""
    v = [("CRC check \"123456789\"", b"123456789"),
         ("IDENTIFY, SEQ 0x00", command("IDENTIFY", 0)),
         ("STATUS, SEQ 0x01", command("STATUS", 1)),
         ("GET_RESPONSE, SEQ 0x02", command("GET_RESPONSE", 2)),
         ("SRAM_WRITE 2 words at word $00010: $1234 $ABCD (byte order V1)", sram_write(0x07, 0x00010, [0x1234, 0xABCD])),
         ("SRAM_READ 2 words at word $00010, SEQ 0x08", sram_read(0x08, 0x00010, 2)),
         ("Response OK to SEQ 0x08, data $1234 $ABCD, STATUS 0x00", response(0x00, 0x08, 0, bytes([0x12, 0x34, 0xAB, 0xCD]))),
         ("REG_WRITE idx 10 (QCTL) = $A55A, both lanes, SEQ 0x09", command("REG_WRITE", 9, bytes([10, 0x03, 0xA5, 0x5A]))),
         ("REG_READ idx 13 (AMIGA_STATUS), SEQ 0x0A", command("REG_READ", 10, bytes([13]))),
         ("ECHO 01 02 03, SEQ 0x0B", command("ECHO", 11, bytes([1, 2, 3])))]
    return v


def main(argv):
    if len(argv) >= 2 and argv[1] == "vectors":
        print("| Vector | Bytes (hex, transmission order) | CRC-16 |")
        print("|---|---|---|")
        for name, b in vectors():
            if name.startswith("CRC check"):
                print(f"| {name} | `{b.hex(' ')}` (ASCII) | 0x{crc16(b):04X} |")
            else:
                print(f"| {name} | `{b.hex(' ')}` | 0x{(b[-2] << 8) | b[-1]:04X} |")
        return 0
    if len(argv) >= 3 and argv[1] == "vh":
        lines = ["// Generated by tools/hostlink/hostlink.py vh. Host-link protocol v1.0 test vectors.",
                 f"localparam integer HL_NVEC = {len(vectors()) - 1};"]
        for i, (name, b) in enumerate(vectors()[1:]):
            lines.append(f"// {i}: {name}")
            lines.append(f"localparam integer HL_V{i}_LEN = {len(b)};")
            lines.append(f"localparam [{8 * len(b) - 1}:0] HL_V{i} = {8 * len(b)}'h{b.hex()};")
        open(argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
        return 0
    print(__doc__)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
