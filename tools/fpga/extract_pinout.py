"""Write a facts-only TQFP144 extract of a Lattice MachXO2 pinout CSV.

usage: python -I tools/fpga/extract_pinout.py <lattice pinout .csv> <out .csv> <device> <document id> <revision>

The repository does not redistribute Lattice's pinout files (NOTICE.md). It keeps only the pin facts that
the tools use, for the one package on this board. Each extract records the source document, its revision
and the SHA-256 of the file it came from, so anyone can download the original and regenerate or check
the extract. Columns keep the source names, so the loaders in pinplan.py and sheet2.py read either file.
"""
from __future__ import annotations

import csv
import hashlib
import sys
from pathlib import Path

COLUMNS = ["PAD", "Pin/Ball Function", "Bank", "Dual Function", "Differential", "TQFP144"]


def main(src: Path, out: Path, device: str, doc: str, rev: str) -> int:
    raw = src.read_bytes()
    rows = list(csv.reader(raw.decode("utf-8", errors="replace").splitlines()))
    h = next(i for i, r in enumerate(rows) if r and r[0] == "PAD")
    hdr = rows[h]
    keep = []
    for r in rows[h + 1:]:
        if not r or not r[0].strip():
            continue
        d = dict(zip(hdr, r))
        if d.get("TQFP144", "-") not in ("-", ""):
            keep.append([d[c] for c in COLUMNS])
    keep.sort(key=lambda r: int(r[-1]))
    pins = [int(r[-1]) for r in keep]
    if pins != list(range(1, 145)):
        print(f"expected TQFP144 pins 1-144, got {len(pins)} entries")
        return 1
    with out.open("w", encoding="utf-8", newline="") as f:
        f.write(f"# Facts-only extract (TQFP144 package) of the Lattice {device} Pinout, document {doc}, revision {rev}.\n"
                f"# Source file SHA-256 {hashlib.sha256(raw).hexdigest()}. Generated by tools/fpga/extract_pinout.py;\n"
                f"# columns as in the source. Full file: https://www.latticesemi.com/view_document?document_id={doc}\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(COLUMNS)
        w.writerows(keep)
    print(f"{out}: {len(keep)} pins")
    return 0


if __name__ == "__main__":
    sys.exit(main(Path(sys.argv[1]), Path(sys.argv[2]), *sys.argv[3:6]))
